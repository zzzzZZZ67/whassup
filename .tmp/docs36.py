import pathlib, sys

def patch(path, pairs):
    p = pathlib.Path(path)
    s = p.read_text(encoding="utf-8")
    for old, new in pairs:
        if old not in s:
            print("NOT FOUND in", path, ":", old[:70])
            sys.exit(1)
        s = s.replace(old, new, 1)
    p.write_text(s, encoding="utf-8")
    print("WROTE", path, len(s))

